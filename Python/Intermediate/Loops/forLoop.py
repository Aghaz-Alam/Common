'''
6. Loops (for)
for loop → fixed iterations
'''
#✅ Program
def main():
    for i in range(1, 6):
        print(i, end=" ")

if __name__ == "__main__":
    main()

'''
🖥 Output
1 2 3 4 5
'''





# for
def main():
    for i in range(3):
        print("Hello")

if __name__ == "__main__":
    main()

'''
🖥 Output
Hello
Hello
Hello
'''
