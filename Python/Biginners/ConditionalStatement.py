'''
5. Conditional Statements
Used for decision making
if, elif, else
'''

#✅ Program
def main():
    marks = 85

    if marks >= 90:
        print("Grade A")
    elif marks >= 75:
        print("Grade B")
    else:
        print("Grade C")

if __name__ == "__main__":
    main()


'''
🖥 Output
Grade B
'''