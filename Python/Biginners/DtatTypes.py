'''
2. Data Types
int, float, str, bool
Use type() to check data type
'''
#✅ Program
def main():
    a = 10
    b = 3.5
    c = "Python"
    d = True

    print(type(a))
    print(type(b))
    print(type(c))
    print(type(d))

if __name__ == "__main__":
    main()
'''
🖥 Output
<class 'int'>
<class 'float'>
<class 'str'>
<class 'bool'>
'''